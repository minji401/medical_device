const PRODUCTS = WELFARE_PRODUCTS.map(function (p) {
  return Object.assign({ group: "welfare" }, p);
}).concat(buildUninsured(), buildDisability());

function copay(price, rate) {
  return Math.round(price * (rate == null ? 0.15 : rate));
}

function won(n) {
  return n.toLocaleString("ko-KR") + "원";
}

function productById(id) {
  return PRODUCTS.find(function (p) { return p.id === id; });
}

function groupName(id) {
  return (GROUPS.find(function (g) { return g.id === id; }) || {}).name || id;
}

function categoryName(id) {
  return (CATEGORIES.find(function (c) { return c.id === id; }) || {}).name || id;
}

function categoryMeta(id) {
  return CATEGORIES.find(function (c) { return c.id === id; }) || {};
}

function productGroup(p) {
  return p.group || categoryMeta(p.category).group || "welfare";
}

function isWelfare(p) {
  return productGroup(p) === "welfare";
}

function categoriesByGroup(group) {
  if (!group || group === "all") return CATEGORIES;
  return CATEGORIES.filter(function (c) { return c.group === group; });
}

function productsByFilter(opts) {
  opts = opts || {};
  return PRODUCTS.filter(function (p) {
    const g = productGroup(p);
    if (opts.group && opts.group !== "all" && g !== opts.group) return false;
    if (opts.category && opts.category !== "all" && p.category !== opts.category) return false;
    if (opts.mode && opts.mode !== "all" && p.mode !== opts.mode && p.mode !== "both") return false;
    if (opts.featured && !(p.badges || []).includes("hot")) return false;
    if (opts.q) {
      const hay = (p.name + p.desc + categoryName(p.category) + groupName(g)).toLowerCase();
      if (hay.indexOf(opts.q.toLowerCase()) < 0) return false;
    }
    return true;
  });
}
