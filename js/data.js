function hash32(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function productFrom(partial) {
  const h = hash32(partial.id);
  const badges = (partial.badges || []).slice();
  if (!badges.length) {
    if (h % 13 === 0) badges.push("hot");
    else if (h % 3 === 0) badges.push("ship");
  }
  if (partial.group === "uninsured" && !badges.includes("cash")) badges.push("cash");
  if (partial.group === "disability" && !badges.includes("aid")) badges.push("aid");
  return Object.assign({
    mode: "buy",
    rating: Math.round((4.4 + (h % 6) / 10) * 10) / 10,
    reviews: 8 + (h % 320)
  }, partial, { badges });
}

function addModels(out, cat, group, kind, desc, baseSpec, rows) {
  rows.forEach(([id, label, price, spec, extra]) => {
    out.push(productFrom(Object.assign({
      id: cat + "-" + id,
      name: label.indexOf(kind) === 0 ? label : kind + " " + label,
      category: cat,
      group,
      price,
      desc,
      specs: Object.assign({}, baseSpec, spec || {})
    }, extra || {})));
  });
}

function addMatrix(out, cat, group, kind, desc, baseSpec, axes, priceFn, extra) {
  function rec(i, codes, labels, specAcc) {
    if (i === axes.length) {
      const code = codes.join("-");
      out.push(productFrom(Object.assign({
        id: cat + "-" + code,
        name: (kind + " " + labels.join(" ")).trim(),
        category: cat,
        group,
        price: priceFn(labels, specAcc),
        desc,
        specs: Object.assign({}, baseSpec, specAcc)
      }, extra || {})));
      return;
    }
    axes[i].values.forEach(([code, label, spec]) => {
      const nextSpec = Object.assign({}, specAcc, spec || {});
      nextSpec[axes[i].key] = label;
      rec(i + 1, codes.concat(code), labels.concat(label), nextSpec);
    });
  }
  rec(0, [], [], {});
}

